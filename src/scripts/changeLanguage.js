export function initLanguages() {
  const langButtons = document.querySelectorAll('.languages__button');
  const i18nElements = document.querySelectorAll('[data-i18n]');

  const translatePage = (lang) => {
    i18nElements.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const translation = translations[lang][key];

      if (translation) {
        if (el.hasAttribute('placeholder')) {
          el.setAttribute('placeholder', translation);
        } else {
          el.textContent = translation;
        }
      }
    });
  };

  const updateButtonStyles = (activeLang) => {
    langButtons.forEach((btn) => {
      const isTarget = btn.classList.contains(
        `languages__button--${activeLang.toLowerCase()}`,
      );

      btn.classList.toggle('languages__button--active', isTarget);
    });
  };

  const setLanguage = (lang) => {
    window.localStorage.setItem('selectedLanguage', lang);
    translatePage(lang);
    updateButtonStyles(lang);
    document.documentElement.lang = lang.toLowerCase();
  };

  langButtons.forEach((btn) => {
    btn.addEventListener('click', () => {
      const newLang = btn.classList.contains('languages__button--ua')
        ? 'UA'
        : 'EN';

      setLanguage(newLang);
    });
  });

  const savedLang = window.localStorage.getItem('selectedLanguage') || 'EN';

  setLanguage(savedLang);
}
